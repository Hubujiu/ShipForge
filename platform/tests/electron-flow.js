async (page) => {
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  const nav = page.getByRole("navigation", { name: "工作区导航" });
  const button = (name) => page.getByRole("button", { name, exact: true });
  const visible = (locator) => locator.waitFor({ state: "visible", timeout: 15000 });
  const activate = async (locator) => { await visible(locator); await locator.press("Enter"); };
  const choose = (name) => activate(nav.getByRole("button", { name, exact: true }));
  const currentDialog = () => page.getByRole("dialog").last();
  const save = () => activate(currentDialog().getByRole("button", { name: "保存", exact: true }));
  const label = (name) => currentDialog().getByLabel(name, { exact: true });
  const choice = (name) => currentDialog().getByRole("combobox", { name, exact: true });
  const pass = "desk-qa-" + Math.random().toString(36).slice(2) + Math.random().toString(36).slice(2);
  await page.getByLabel("服务地址").fill("http://127.0.0.1:4793");
  await activate(button("检查并继续"));
  await visible(page.getByRole("heading", { name: "创建工作区" }));
  await page.getByLabel("显示名称").fill("测试负责人");
  await page.getByLabel("用户名").fill("desktop-fixture");
  await page.getByLabel("密码", { exact: true }).fill(pass);
  await page.getByLabel("组织名称").fill("示例交付团队");
  await page.getByLabel("初始空间").fill("桌面验收");
  await activate(button("创建并进入"));
  await visible(page.getByRole("heading", { name: "开始使用" }));
  await activate(button("新建任务"));
  await label("任务标题").fill("验证安装版的任务交付");
  await label("任务描述").fill("由本机 Agent 执行并把摘要保存到原对话。");
  await save();
  await visible(page.getByRole("heading", { name: "验证安装版的任务交付", exact: true }));
  await page.getByLabel("添加评论").fill("验收步骤已确认。");
  await activate(button("发送评论"));
  await visible(page.getByText("验收步骤已确认。", { exact: true }));
  await activate(button("关闭"));
  await activate(button("连接本机"));
  await label("机器名称").fill("Windows 验收工作机");
  await activate(button("启用工作机"));
  await visible(page.locator('progress[value="2"]'));
  await choose("Agent");
  await activate(page.getByRole("button", { name: "创建 Agent", exact: true }).first());
  await label("Agent 名称").fill("验收 Agent");
  await label("执行指令").fill("检查任务上下文，回传简要结果。");
  await save();
  await visible(page.getByRole("heading", { name: "验收 Agent", exact: true }));
  await choose("空间任务");
  await activate(page.getByRole("button", { name: /验证安装版的任务交付/ }));
  await activate(button("编辑任务"));
  await choice("处理人或 Agent").selectOption({ label: "验收 Agent" }, { force: true });
  await choice("状态").selectOption("todo", { force: true });
  await save();
  await visible(page.locator(".run-item").getByText("已完成", { exact: true }));
  await page.screenshot({ path: "dist/qa-task-result.png" });
  await activate(button("查看对话"));
  await visible(page.locator(".message").getByText("验收 Agent", { exact: true }));
  await page.screenshot({ path: "dist/qa-conversation.png" });
  await activate(page.getByRole("button", { name: /开始使用/ }));
  await visible(page.locator('progress[value="4"]'));
  await page.screenshot({ path: "dist/qa-onboarding.png" });
  if (errors.length) throw new Error(errors.join("\n"));
  return "Verified initial setup, onboarding, task creation, comments, work machine, Agent assignment and execution result in the Electron window.";
}
